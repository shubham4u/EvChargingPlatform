-- Transactional outbox: events are written here in the same transaction as the change they describe,
-- and published to Kafka by the relay after commit. id gives publishing order.
CREATE TABLE outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic VARCHAR(100) NOT NULL,
    event_key VARCHAR(100),
    event_type VARCHAR(255) NOT NULL,
    payload VARCHAR(8000) NOT NULL,
    trace_id VARCHAR(32),
    span_id VARCHAR(16),
    created_at TIMESTAMPTZ NOT NULL,
    published_at TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error VARCHAR(1000)
);
CREATE INDEX idx_outbox_unpublished ON outbox_events(published_at, id);
